#!/usr/bin/env bash
set -euo pipefail

# Generates the audio visualizer desktop widgets for every connected output, centered on each
# output's logical width, so the spectrum follows monitor and laptop panel changes.
# Usage: visualizer_layout.sh [--print]
#   --print  write the TOML to stdout instead of the config file

readonly OUTPUT_FILE="${HOME}/.config/noctalia/visualizer.toml"
readonly BOX_WIDTH=330
readonly OVERLAP=72
readonly BOX_HEIGHT=32
readonly CY=50

function connected_outputs() {
    niri msg -j outputs 2>/dev/null \
        | jq -r 'to_entries[] | select(.value.logical != null) | "\(.key) \(.value.logical.width)"'
}

# emit_half <id> <output> <cx> <flip_x>
function emit_half() {
    local id="${1}" output="${2}" cx="${3}" flip_x="${4}"

    printf '\n[desktop_widgets.widget.%s]\n' "${id}"
    printf 'type = "audio_visualizer"\n'
    printf 'output = "%s"\n' "${output}"
    printf 'cx = %s\n' "${cx}"
    printf 'cy = %s.0\n' "${CY}"
    printf 'box_width = %s.0\n' "${BOX_WIDTH}"
    printf 'box_height = %s.0\n' "${BOX_HEIGHT}"
    [[ "${flip_x}" == "true" ]] && printf 'flip_x = true\n'
    printf 'flip_y = true\n'
    printf '\n[desktop_widgets.widget.%s.settings]\n' "${id}"
    printf 'bands = 128\n'
    printf 'background = false\n'
    printf 'background_padding = 0.0\n'
    printf 'mirrored = false\n'
    printf 'centered = false\n'
    printf 'show_when_idle = false\n'
    printf 'color_1 = "primary"\n'
    printf 'color_2 = "secondary"\n'
}

function generate() {
    local name width cx_left cx_right
    local -a order=()
    local body=""

    while read -r name width; do
        [[ -n "${name}" ]] || continue
        cx_left="$(awk -v w="${width}" -v b="${BOX_WIDTH}" -v o="${OVERLAP}" 'BEGIN { printf "%.1f", w / 2 - (b - o) / 2 }')"
        cx_right="$(awk -v w="${width}" -v b="${BOX_WIDTH}" -v o="${OVERLAP}" 'BEGIN { printf "%.1f", w / 2 + (b - o) / 2 }')"
        order+=("\"audio-${name}-left\"" "\"audio-${name}-right\"")
        body+="$(emit_half "audio-${name}-left" "${name}" "${cx_left}" true)"$'\n'
        body+="$(emit_half "audio-${name}-right" "${name}" "${cx_right}" false)"$'\n'
    done < <(connected_outputs)

    [[ "${#order[@]}" -gt 0 ]] || return 1

    printf '# Generated by visualizer_layout.sh, do not edit. The two halves overlap by %s px so the\n' "${OVERLAP}"
    printf '# dead zone of the lowest bands closes at the middle of each output.\n'
    printf '[desktop_widgets]\nenabled = true\nschema_version = 2\n'
    printf 'widget_order = [%s]\n' "$(IFS=,; printf '%s' "${order[*]}" | sed 's/,/, /g')"
    printf '%s' "${body}"
}

function main() {
    if [[ "${1:-}" == "--print" ]]; then
        generate
        return
    fi

    local tmp
    tmp="$(mktemp)"
    generate > "${tmp}" || { rm -f "${tmp}"; return 0; }

    if [[ -f "${OUTPUT_FILE}" ]] && cmp -s "${tmp}" "${OUTPUT_FILE}"; then
        rm -f "${tmp}"
        return 0
    fi

    mv "${tmp}" "${OUTPUT_FILE}"
    noctalia msg config-reload >/dev/null 2>&1 || true
}

main "$@"
