#!/usr/bin/env bash
set -euo pipefail

# Generates the lock screen widgets for every common output name plus any connected one, so the
# same design applies on each screen, even one plugged in while locked: v5 only stores lock
# screen widgets per output, and its editor writes entries for just the output it was used on.
# The design is the one built by hand in the lock screen editor on DP-3: an analog clock and a
# compact login box. Positions are fractions of each output's logical height.
# Usage: lockscreen_layout.sh [--print]
#   --print  write the TOML to stdout instead of the config file
# v5 also copies the layout into its state file, which wins over this file, so a changed
# value needs that section removed from the state file while v5 is stopped.

readonly OUTPUT_FILE="${HOME}/.config/noctalia/lockscreen-widgets.toml"
readonly CLOCK_WIDTH=429.3
readonly CLOCK_HEIGHT=302.8
readonly CLOCK_Y=0.4607
readonly LOGIN_WIDTH=400.0
readonly LOGIN_HEIGHT=70.0
readonly LOGIN_Y=0.6556
readonly REF_WIDTH=1920
readonly REF_HEIGHT=1080
readonly KNOWN_OUTPUTS=(
    eDP-1 eDP-2
    DP-1 DP-2 DP-3 DP-4 DP-5 DP-6 DP-7 DP-8
    HDMI-A-1 HDMI-A-2 HDMI-A-3
    DP-1-1 DP-1-2 DP-1-3 DP-2-1 DP-2-2 DP-2-3
)

# Known names first, then any connected output not among them, in a stable order so the
# generated file only changes when a new connector name shows up
function all_outputs() {
    local name
    printf '%s\n' "${KNOWN_OUTPUTS[@]}"
    while read -r name; do
        [[ -n "${name}" && " ${KNOWN_OUTPUTS[*]} " != *" ${name} "* ]] && printf '%s\n' "${name}"
    done < <(niri msg -j outputs 2>/dev/null | jq -r 'keys[]' | sort)
}

# emit_widget <id> <type> <output> <width> <height> <cx> <cy> <box_w> <box_h>
function emit_widget() {
    printf '\n[lockscreen_widgets.widget."%s"]\n' "${1}"
    printf 'type = "%s"\n' "${2}"
    printf 'output = "%s"\n' "${3}"
    printf 'cx = %s\n' "${6}"
    printf 'cy = %s\n' "${7}"
    printf 'box_width = %s\n' "${8}"
    printf 'box_height = %s\n' "${9}"
    printf 'placement_width = %s.0\n' "${4}"
    printf 'placement_height = %s.0\n' "${5}"
    printf 'rotation = 0.0\n'
}

function generate() {
    local name width="${REF_WIDTH}" height="${REF_HEIGHT}" cx cy_clock cy_login
    local -a order=()
    local body=""

    while read -r name; do
        [[ -n "${name}" ]] || continue
        cx="$(awk -v w="${width}" 'BEGIN { printf "%.1f", w / 2 }')"
        cy_clock="$(awk -v h="${height}" -v y="${CLOCK_Y}" 'BEGIN { printf "%.1f", h * y }')"
        cy_login="$(awk -v h="${height}" -v y="${LOGIN_Y}" 'BEGIN { printf "%.1f", h * y }')"
        order+=("\"lockscreen-widget-clock-${name}\"" "\"lockscreen-login-box@${name}\"")

        body+="$(emit_widget "lockscreen-widget-clock-${name}" clock "${name}" "${width}" "${height}" "${cx}" "${cy_clock}" "${CLOCK_WIDTH}" "${CLOCK_HEIGHT}")"$'\n'
        body+=$'\n'"[lockscreen_widgets.widget.\"lockscreen-widget-clock-${name}\".settings]"$'\n'
        body+=$'background = false\nclock_style = "analog"\ncolor = "primary"\nformat = "{:%H:%M}"\n'

        body+="$(emit_widget "lockscreen-login-box@${name}" login_box "${name}" "${width}" "${height}" "${cx}" "${cy_login}" "${LOGIN_WIDTH}" "${LOGIN_HEIGHT}")"$'\n'
        body+=$'\n'"[lockscreen_widgets.widget.\"lockscreen-login-box@${name}\".settings]"$'\n'
        body+=$'layout = "compact"\ncenter_password_text = true\ninput_opacity = 0.5\nshow_login_button = false\nshow_unlock_hint = false\n'
    done < <(all_outputs)

    [[ "${#order[@]}" -gt 0 ]] || return 1

    printf '# Generated by lockscreen_layout.sh, do not edit. Delete this file to get the default lock screen.\n'
    printf '[lockscreen_widgets]\nenabled = true\nschema_version = 2\n'
    printf 'widget_order = [%s]\n' "$(IFS=,; printf '%s' "${order[*]}" | sed 's/,/, /g')"
    printf '%s' "${body}"
}

function main() {
    if [[ "${1:-}" == "--print" ]]; then
        generate
        return
    fi

    local tmp
    tmp="$(mktemp)"
    generate > "${tmp}" || { rm -f "${tmp}"; return 0; }

    if [[ -f "${OUTPUT_FILE}" ]] && cmp -s "${tmp}" "${OUTPUT_FILE}"; then
        rm -f "${tmp}"
        return 0
    fi

    mv "${tmp}" "${OUTPUT_FILE}"
    chmod 644 "${OUTPUT_FILE}"
    noctalia msg config-reload >/dev/null 2>&1 || true
}

main "$@"
