#!/usr/bin/env bash
set -euo pipefail

# Centers the logo in the Noctalia bar by retuning the sp-lead spacer.
# The clock has no fixed width, so its text width (day and month names) shifts the logo off
# center. This measures where the logo really renders, then nudges sp-lead until it is centered.
# The value goes in center.toml (untracked), never in bar.toml.
# Usage: noctalia_center_logo.sh [--dry-run] [--help]
#   --dry-run  measure and report the offset without changing anything

readonly CONFIG_DIR="${HOME}/.config/noctalia"
readonly OVERRIDE_FILE="${CONFIG_DIR}/center.toml"
readonly BAR_FILE="${CONFIG_DIR}/bar.toml"
readonly MAX_PASSES=4
readonly TOLERANCE=0.6
# logical px either side of the screen center scanned for the logo, small enough to skip the
# album art that sits further right
readonly SCAN_HALF=22
# physical px from the top, kept inside the bar so colored window content below is ignored
readonly BAR_HEIGHT=44

readonly RED='\033[38;2;243;139;168m'
readonly GREEN='\033[38;2;166;227;161m'
readonly BLUE='\033[38;2;137;180;250m'
readonly TEAL='\033[38;2;148;226;213m'
readonly RESET='\033[0m'

function print_info()    { printf "${BLUE}[INFO]${RESET} %s\n" "$*"; }
function print_success() { printf "${GREEN}[OK]${RESET} %s\n" "$*"; }
function print_error()   { printf "${RED}[ERROR]${RESET} %s\n" "$*" >&2; }
function print_dry_run() { printf "${TEAL}[DRY-RUN]${RESET} %s\n" "$*"; }

function usage() {
    sed -n '4,9p' "${0}" | sed 's/^# \{0,1\}//'
}

function current_length() {
    local source_file
    for source_file in "${OVERRIDE_FILE}" "${BAR_FILE}"; do
        [[ -f "${source_file}" ]] || continue
        awk '
            /^\[/ { in_sec = ($0 == "[widget.sp-lead]") }
            in_sec && /^length[[:space:]]*=/ { gsub(/[^0-9.]/, "", $0); print; exit }
        ' "${source_file}" | grep . && return 0
    done
    return 1
}

function compositor() {
    if [[ -n "${NIRI_SOCKET:-}" ]]; then
        printf 'niri'
    elif [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]]; then
        printf 'hyprland'
    elif [[ -n "${SWAYSOCK:-}" ]]; then
        printf 'sway'
    else
        return 1
    fi
}

# Prints "name scale logical_width" of the focused output
function focused_output() {
    case "$(compositor)" in
        niri)
            niri msg --json focused-output \
                | jq -r '[.name, .logical.scale, .logical.width] | join(" ")' ;;
        hyprland)
            hyprctl -j monitors \
                | jq -r '.[] | select(.focused) | [.name, .scale, (.width / .scale | floor)] | join(" ")' ;;
        sway)
            swaymsg -t get_outputs -r \
                | jq -r '.[] | select(.focused) | [.name, .scale, .rect.width] | join(" ")' ;;
    esac
}

# Prints the logo center offset from the screen center, in logical px (negative is left)
function measure_offset() {
    local output scale width tmp scan_px center_px
    read -r output scale width < <(focused_output)
    tmp="$(mktemp -d)"
    trap 'rm -rf "${tmp}"' RETURN

    center_px="$(awk -v w="${width}" -v s="${scale}" 'BEGIN { printf "%d", w * s / 2 }')"
    scan_px="$(awk -v h="${SCAN_HALF}" -v s="${scale}" 'BEGIN { printf "%d", h * s }')"

    grim -o "${output}" "${tmp}/full.png"
    magick "${tmp}/full.png" -crop "$((scan_px * 2))x${BAR_HEIGHT}+$((center_px - scan_px))+0" \
        +repage -depth 8 txt:- |
        awk -F'[(), ]+' -v origin="$((center_px - scan_px))" -v center="${center_px}" -v s="${scale}" '
            NR > 1 {
                split($1, pos, ","); x = pos[1] + 0
                r = $3; g = $4; b = $5
                max = r; if (g > max) max = g; if (b > max) max = b
                min = r; if (g < min) min = g; if (b < min) min = b
                # saturated and bright: the colorized logo, not the gray text
                if (max > 110 && (max - min) / max > 0.3) { n++; sum += x }
            }
            END {
                if (n < 20) exit 1
                printf "%.2f\n", ((sum / n + origin) - center) / s
            }'
}

function write_length() {
    printf '# generated by noctalia_center_logo.sh, not tracked\n[widget.sp-lead]\nlength = %s\n' \
        "${1}" > "${OVERRIDE_FILE}"
}

function main() {
    local dry_run=0 pass offset length new_length
    case "${1:-}" in
        -h|--help) usage; return 0 ;;
        --dry-run) dry_run=1 ;;
    esac

    local comp comp_cmd
    comp="$(compositor)" || { print_error "no supported compositor in the environment"; return 1; }
    case "${comp}" in
        niri)     comp_cmd="niri" ;;
        hyprland) comp_cmd="hyprctl" ;;
        sway)     comp_cmd="swaymsg" ;;
    esac
    for cmd in "${comp_cmd}" jq grim magick noctalia; do
        command -v "${cmd}" >/dev/null || { print_error "missing command: ${cmd}"; return 1; }
    done

    length="$(current_length)" || { print_error "sp-lead length not found"; return 1; }

    for pass in $(seq 1 "${MAX_PASSES}"); do
        offset="$(measure_offset)" || { print_error "logo not found near screen center"; return 1; }
        print_info "pass ${pass}: logo offset ${offset}px, sp-lead ${length}"

        if awk -v o="${offset}" -v t="${TOLERANCE}" 'BEGIN { exit !(o < t && o > -t) }'; then
            print_success "logo centered"
            return 0
        fi
        if [[ "${dry_run}" -eq 1 ]]; then
            print_dry_run "would retune sp-lead from ${length}"
            return 0
        fi

        # the centered group grows with the spacer, so the logo moves right by d / 2
        new_length="$(awk -v l="${length}" -v o="${offset}" \
            'BEGIN { v = int(l - 2 * o + (o < 0 ? 0.5 : -0.5)); if (v < 0) v = 0; if (v > 200) v = 200; print v }')"
        write_length "${new_length}"
        length="${new_length}"
        noctalia msg config-reload >/dev/null
        sleep 1
    done
    print_error "not centered after ${MAX_PASSES} passes"
    return 1
}

main "$@"
